export type TarotSuit = 'wands' | 'cups' | 'swords' | 'pentacles';
export type TarotTopic = 'general' | 'love' | 'work';
export type YesNo = -1 | 0 | 1;

type Meanings = Record<TarotTopic, string>;

export interface TarotCard {
  /** 0–21 Ẩn chính; 22–77 Ẩn phụ theo thứ tự Gậy, Cốc, Kiếm, Tiền */
  id: number;
  name: string;
  en: string;
  arcana: 'major' | 'minor';
  suit?: TarotSuit;
  /** Ẩn chính: 0–21; Ẩn phụ: 1–14 (11 Tiểu Đồng, 12 Hiệp Sĩ, 13 Hoàng Hậu, 14 Vua) */
  rank: number;
  keywords: string[];
  reversedKeywords: string[];
  up: Meanings;
  rev: Meanings;
  advice: string;
  /** Khuynh hướng khi hỏi có/không, ở chiều xuôi */
  yes: YesNo;
}

