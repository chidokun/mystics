export const getTarotCard = (id: number): TarotCard => {
  const card = CARDS[id];
  if (!card || card.id !== id) throw new Error(`Không có lá Tarot số ${id}`);
  return card;
};

/** Nhãn ngắn ở đầu lá: số La Mã cho Ẩn chính, thứ hạng cho Ẩn phụ */
export const cardNumeral = (c: TarotCard): string => {
  if (c.arcana === 'major') return ROMAN[c.rank];
  if (c.rank === 1) return 'Át';
  if (c.rank <= 10) return String(c.rank);
  return RANK_NAMES[c.rank];
};

