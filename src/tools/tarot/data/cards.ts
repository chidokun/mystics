const m = (g: string, l: string, w: string): Meanings => ({ general: g, love: l, work: w });

const major = (
  rank: number,
  name: string,
  en: string,
  yes: YesNo,
  keywords: string[],
  reversedKeywords: string[],
  up: Meanings,
  rev: Meanings,
  advice: string,
): TarotCard => ({ id: rank, name, en, arcana: 'major', rank, keywords, reversedKeywords, up, rev, advice, yes });

const SUIT_ORDER: TarotSuit[] = ['wands', 'cups', 'swords', 'pentacles'];

const minor = (
  suit: TarotSuit,
  rank: number,
  yes: YesNo,
  keywords: string[],
  reversedKeywords: string[],
  up: Meanings,
  rev: Meanings,
  advice: string,
): TarotCard => ({
  id: 22 + SUIT_ORDER.indexOf(suit) * 14 + (rank - 1),
  name: `${RANK_NAMES[rank]} ${SUITS[suit].name}`,
  en: `${RANK_EN[rank]} of ${SUITS[suit].en}`,
  arcana: 'minor',
  suit,
  rank,
  keywords,
  reversedKeywords,
  up,
  rev,
  advice,
  yes,
});

